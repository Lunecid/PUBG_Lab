#!/usr/bin/env python3
"""Rebuild the paper's derived tables and copy the aggregator's tables/figures.

Run from the repository root or from this folder after re-running the aggregator:
    python3 projects/battle_royale/reporting/make_paper_tables.py [--results-dir reports/bigcomp2027_results_v2] [--paper-dir paper/bigcomp2027]
Inputs: <results-dir>/*.csv, tables/*.tex, figures/*.pdf (numbers are read, never typed); the default results directory is the v2 root of
model_stgcn.ptr.paths.  With --dump-dir its meta.version must match the version of the results directory: a v1 results directory next to the
v2 dump (or the reverse) is refused (tools/rerun_v2.py always passes it).
Outputs (in <paper-dir>/tables and figures): tab_primary.tex (rebuilt), tab_arms.tex, tab_external_short.tex, tab_metareg.tex, forest_primary.pdf,
learning_curve.pdf (when the learning curve was run), and copies of the aggregator's tab_decomp.tex (the single-factor steps and the rank auxiliary
loss), tab_rq2_external.tex (the bundled external contrasts) and tab_grid.tex.  Prose numbers in sections/*.tex are typed by hand and must be
rechecked against the CSVs (and tools/paper_numbers_v2.py: reports/bigcomp2027_results_v2/paper_numbers.json) after a re-run.
"""

# Canonical working copy; the paper's original source remains frozen.
if not __package__:
    import sys as _pkg_sys
    from pathlib import Path as _PackagePath

    _workspace = _PackagePath(__file__).resolve().parents[3]
    _pkg_sys.path.insert(0, str(_workspace))
    _pkg_sys.path.insert(0, str(_workspace / "src"))
from pubg_lab.common.paths import REPO_ROOT

import argparse
import shutil
import sys
from pathlib import Path

import pandas as pd

REPO = REPO_ROOT
PAPER = REPO / "paper/bigcomp2027"
HERE = PAPER / "tables"
if str(REPO) not in sys.path:
    sys.path.insert(0, str(REPO))

import pubg_lab.survival.ptr.data.paths as P  # noqa: E402  (the v2 roots and the version guard)

RES = (
    P.RESULTS_DIR
)  # default of --results-dir (the v2 root); every function below takes the directory explicitly
COPIED_TABLES = (
    "tab_decomp.tex",
    "tab_rq2_external.tex",
    "tab_grid.tex",
)  # written by the aggregator, copied verbatim


def fmt(x, d=3):
    return f"{x:.{d}f}"


def signed(x, d=3):
    s = f"{abs(x):.{d}f}"
    return ("+" if x >= 0 else "$-$") + s


def delta(row, d=3):
    return f"{signed(row.theta, d)} [{signed(row.ci95_low, d)[0:0]}{fmt(row.ci95_low, d) if row.ci95_low >= 0 else '$-$' + fmt(-row.ci95_low, d)}, {fmt(row.ci95_high, d) if row.ci95_high >= 0 else '$-$' + fmt(-row.ci95_high, d)}]"


def write_primary(res=RES, paper=PAPER):
    """Primary-contrast table: same layout as the aggregator's tab_primary, with four decimals so that the
    table agrees with the prose (three decimals print values such as +0.000 [-0.000, 0.001])."""
    d = pd.read_csv(Path(res) / "contrasts_pooled.csv")
    d = d[(d.kind == "primary") & (d.stratum == "all")].set_index("primary_id")
    names = {
        "P1": ("P1 (RQ1)", "phase-axis main effect", "AUC"),
        "P2": ("P2 (RQ2)", "team-axis main effect", "AUC"),
        "P3": ("P3 (RQ2)", "team-axis main effect", "Spearman"),
        "P4": ("P4 (RQ3)", "M11R $-$ M11R-shuf", "AUC"),
        "P5": ("P5 (RQ4)", "M11RZ-noHab $-$ M11R-noHab", "AUC"),
    }

    def num(x, dd=4):
        return fmt(x, dd) if x >= 0 else "$-$" + fmt(-x, dd)

    def tau(t):
        m, e = f"{t:.1e}".split("e")
        return f"${m}\\!\\times\\!10^{{{int(e)}}}$"

    rows = []
    for pid, (lab, con, met) in names.items():
        r = d.loc[pid]
        ph = "$<$0.001" if r.p_holm < 0.001 else fmt(r.p_holm, 3)
        rows.append(
            f"{lab} & {con} & {met} & {signed(r.theta, 4)} [{num(r.ci95_low)}, {num(r.ci95_high)}] & "
            f"{int(r.same_sign)} & {tau(r.tau2)} & {ph} & {r.verdict} \\\\"
        )
    k = int(d.loc["P1"].k)
    head = (
        "% generated by paper/bigcomp2027/tables/make_paper_tables.py from <results-dir>/contrasts_pooled.csv (v2: reports/bigcomp2027_results_v2)\n"
        "% (layout of the aggregator's tab_primary; intervals with four decimals). One-sided pooled z tests, Holm over P1-P5 only;\n"
        "% the 95% intervals are unadjusted.\n\n"
        "\\begin{tabular}{@{}l l l c c c c c@{}}\n\\toprule\n"
        f" & Contrast & Metric & $\\Delta$ [95\\% CI] & Same sign /${k}$ & $\\tau^2$ & Holm $p$ & Verdict \\\\\n\\midrule\n"
    )
    (Path(paper) / "tables" / "tab_primary.tex").write_text(
        head + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n"
    )


def parse_args(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument(
        "--results-dir",
        type=Path,
        default=RES,
        help="aggregator output (default: the v2 root reports/bigcomp2027_results_v2)",
    )
    ap.add_argument(
        "--paper-dir",
        type=Path,
        default=PAPER,
        help="paper directory with tables/ and figures/ (default: paper/bigcomp2027)",
    )
    ap.add_argument(
        "--dump-dir",
        type=Path,
        default=None,
        help="dump directory, only for the version check against --results-dir (v2: model_stgcn/dumps/bigcomp2027_phase_v2)",
    )
    return ap.parse_args(argv)


def main(argv=None):
    a = parse_args(argv)
    res, paper = Path(a.results_dir), Path(a.paper_dir)
    if a.dump_dir is not None:
        try:
            P.check_same_version(a.dump_dir, {"results (--results-dir)": res})
        except P.VersionMixError as exc:
            raise SystemExit(f"refusing to run: {exc}") from exc
    (paper / "tables").mkdir(parents=True, exist_ok=True)
    (paper / "figures").mkdir(parents=True, exist_ok=True)
    # 1. write the primary table; copy the figures (the learning curve is optional: it is not part of the paper-critical set)
    write_primary(res, paper)
    for f in ("forest_primary.pdf", "learning_curve.pdf"):
        if (res / "figures" / f).is_file():
            shutil.copy(res / "figures" / f, paper / "figures" / f)
        else:
            print(f"warning: {res / 'figures' / f} not found; not copied", file=sys.stderr)
    # NOTE: a steps-matched learning curve (learning_curve_steps.pdf) may replace learning_curve.pdf later.
    # the aggregator's own tables that the paper uses as they are (single-factor steps + rank auxiliary loss, bundled RQ2 contrasts, the C1 grid)
    copied = []
    for name in COPIED_TABLES:
        src = res / "tables" / name
        if src.is_file():
            shutil.copy(src, paper / "tables" / name)
            copied.append(name)
        elif (paper / "tables" / name).is_file():
            (
                paper / "tables" / name
            ).unlink()  # the table does not exist for these runs: no stale copy
    if "tab_decomp.tex" not in copied:
        print(
            f"warning: {res / 'tables' / 'tab_decomp.tex'} not found (no decomposition step was run)",
            file=sys.stderr,
        )

    am = pd.read_csv(res / "arm_metrics_mean.csv")
    am = am[am.stratum == "all"].pivot(index="arm", columns="metric", values="mean")
    k = pd.read_csv(res / "arm_metrics_mean.csv")
    ncoh = k[(k.stratum == "all") & (k.metric == "auc")].set_index("arm")["n_cohorts"]

    # 2. arms + arm-level means (merged arm / metrics table)
    on = r"$\checkmark$"
    rows = [
        ("M00", "", "", "", "", "all"),
        ("M10", on, "", "", "", "all"),
        ("M01", "", on, "", "", "all"),
        ("M11", on, on, "", "", "all"),
        ("M11R", on, on, on, "", "all"),
        ("M11R-shuf", on, on, "shuf.", "", "all"),
        ("M11RZ", on, on, on, on, "all"),
        ("M11R-noHab", on, on, on, "", "no Hab"),
        ("M11RZ-noHab", on, on, on, on, "no Hab"),
    ]
    stage2 = [
        ("M11RZ-P", on, on, on, on, "all$+$pl."),
        ("M11RZ-P-tm", on, on, "no tm", on, "all$+$pl."),
    ]
    refs = [
        ("HGB-cut", "150-d row of phase $k$"),
        ("HGB-lag", "HGB-cut $+$ lag"),
        ("HGB-noHab", "HGB-cut, no Hab"),
    ]

    def metrics(arm):
        r = am.loc[arm]
        return f"{fmt(r['auc'])} & {fmt(r['spearman'])} & {fmt(r['top5_auc'])}"

    lines = [
        "% generated by tables/make_paper_tables.py from <results-dir>/arm_metrics_mean.csv (stratum all, seed 42)",
        r"\begin{tabular}{@{}l c c c c l c c c@{}}",
        r"\toprule",
        r"Arm & Ph. & Tm. & Rel. & Zn. & Features & AUC & Spearman & Top-5 \\",
        r"\midrule",
    ]
    for a, p, t, r_, z, f in rows:
        lines.append(f"{a} & {p} & {t} & {r_} & {z} & {f} & {metrics(a)} \\\\")
    stage2 = [
        row for row in stage2 if row[0] in am.index
    ]  # stage 2 (the player layer) is not part of the v2 re-run: no row for an arm that was not run
    if stage2:
        lines.append("% STAGE2: delete if not run by 10/9")
        for a, p, t, r_, z, f in stage2:
            lines.append(
                f"{a.replace('-tm', '$-$tm')} & {p} & {t} & {r_} & {z} & {f} & {metrics(a)} \\\\"
            )
        lines.append("% STAGE2 end")
    lines.append(r"\midrule")
    for a, d in refs:
        lines.append(f"{a} & \\multicolumn{{5}}{{l}}{{{d}}} & {metrics(a)} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    (paper / "tables" / "tab_arms.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")

    # 3. abbreviated external-baseline table (12-cohort means; pooled delta where the aggregator has one)
    cp = pd.read_csv(res / "contrasts_pooled.csv")
    cp = cp[(cp.stratum == "all") & (cp.metric == "auc")].set_index("contrast")

    def d_auc(c):
        if c not in cp.index:
            return "---"
        r = cp.loc[c]
        lo = fmt(r.ci95_low) if r.ci95_low >= 0 else "$-$" + fmt(-r.ci95_low)
        hi = fmt(r.ci95_high) if r.ci95_high >= 0 else "$-$" + fmt(-r.ci95_high)
        return f"{signed(r.theta)} [{lo}, {hi}]"

    def coh(arm, label):
        n = int(ncoh[arm])
        return f"{label} ({n} coh.)" if n < int(ncoh.max()) else label

    # (arm, row label, contrast of M11R against it); an arm that was not run (K1-mlp, the Sagong re-fits ...) gets no row
    spec = [
        ("SAGONG-xgb", "SAGONG-xgb", "m11r_vs_sagong_xgb"),
        ("SAGONG-lr", "SAGONG-lr", "m11r_vs_sagong_lr"),
        ("SAGONG-rf", "SAGONG-rf", "m11r_vs_sagong_rf"),
        ("KRAFTON-tf", "KRAFTON-tf", "m11r_vs_krafton_tf"),
        ("KRAFTON-tf-h0", "KRAFTON-tf+H0", "m11r_vs_krafton_tf_h0"),
        ("KRAFTON-mlp", "KRAFTON-mlp", "m11r_vs_krafton_mlp"),
        ("KRAFTON-tf-ourfeat", "KRAFTON-tf-ourfeat (K2)", "m11r_vs_krafton_tf_ourfeat"),
        ("KRAFTON-tf-ourfeat-h0", "K2+H0", None),
    ]
    ext = [(a, coh(a, label), d_auc(c) if c else "---") for a, label, c in spec if a in am.index]
    L = [
        "% generated by tables/make_paper_tables.py from <results-dir>/arm_metrics_mean.csv and contrasts_pooled.csv (exploratory, no Holm)",
        r"\begin{tabular}{@{}l c c c c@{}}",
        r"\toprule",
        r"Model & AUC & Spearman & Top-5 AUC & $\Delta$AUC of M11R [95\% CI] \\",
        r"\midrule",
        f"HGB-cut (our features) & {metrics('HGB-cut')} & {d_auc('m11r_vs_hgbcut').replace('+', '+')} \\\\",
        f"M11R (our features) & {metrics('M11R')} & --- \\\\",
        r"\midrule",
    ]
    for a, label, d in ext:
        L.append(f"{label} & {metrics(a)} & {d} \\\\")
    L += [r"\bottomrule", r"\end{tabular}"]
    (paper / "tables" / "tab_external_short.tex").write_text("\n".join(L) + "\n", encoding="utf-8")

    # 4. three-row meta-regression table (exploratory)
    mr = pd.read_csv(res / "metareg.csv").set_index("contrast")
    names = [
        ("m11r_vs_hgbcut", r"M11R $-$ HGB-cut"),
        ("phase_main", r"P1, phase-axis main effect"),
        ("team_main", r"P2, team-axis main effect"),
    ]
    T = [
        "% generated by tables/make_paper_tables.py from <results-dir>/metareg.csv (exploratory)",
        r"\begin{tabular}{@{}l c c c@{}}",
        r"\toprule",
        r"$\Delta$AUC on cohort size & Slope per $\ln N$ [95\% CI] & $p$ & Crossover $N$ [95\% CI] \\",
        r"\midrule",
    ]
    for key, label in names:
        r = mr.loc[key]
        sl = f"{signed(r.slope, 4)} [{fmt(r.ci95_low, 4) if r.ci95_low >= 0 else '$-$' + fmt(-r.ci95_low, 4)}, {fmt(r.ci95_high, 4) if r.ci95_high >= 0 else '$-$' + fmt(-r.ci95_high, 4)}]"
        p = "$<$0.001" if r.p < 0.001 else fmt(r.p, 2)
        cr = (
            "---"
            if pd.isna(r.crossover_ci_low)
            else f"{r.crossover_n:.0f} [{r.crossover_ci_low:.0f}, {r.crossover_ci_high:.0f}]"
        )
        T.append(f"{label} & {sl} & {p} & {cr} \\\\")
    T += [r"\bottomrule", r"\end{tabular}"]
    (paper / "tables" / "tab_metareg.tex").write_text("\n".join(T) + "\n", encoding="utf-8")
    print("tables written:", sorted(p.name for p in (paper / "tables").glob("*.tex")))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
