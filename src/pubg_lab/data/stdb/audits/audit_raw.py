"""
stdb/audit_raw.py
=================
`pubg.*` raw schema를 information_schema에서 읽어 컬럼/타입/row count/NULL
샘플을 `stdb/schema_audit.md` 로 덤프한다. Read-only.

스키마/ETL 작성 전에 한 번 돌려서 추측한 컬럼명이 실제와 맞는지 확인한다.
"""

from __future__ import annotations

# Support explicit direct-file execution as well as package entry points.
if not __package__:
    import sys as _pkg_sys
    from pathlib import Path as _PackagePath

    _workspace = _PackagePath(__file__).resolve().parents[5]
    _pkg_sys.path.insert(0, str(_workspace))
    _pkg_sys.path.insert(0, str(_workspace / "src"))

from pubg_lab.common.paths import REPO_ROOT

from pathlib import Path

import psycopg2

from pubg_lab.data.stdb.connection.conn import DB_CONFIG, require_pg_password

RAW_SCHEMA = "pubg"
OUT_PATH = REPO_ROOT / "projects/data_preparation/docs/schema_audit.md"


def _table_rowcount(cur, schema: str, table: str) -> int | None:
    try:
        cur.execute(f'SELECT count(*) FROM "{schema}"."{table}"')
        return cur.fetchone()[0]
    except Exception:
        cur.execute("ROLLBACK")
        return None


def _column_sample(cur, schema: str, table: str, column: str) -> str:
    try:
        cur.execute(
            f'SELECT "{column}" FROM "{schema}"."{table}" WHERE "{column}" IS NOT NULL LIMIT 1'
        )
        row = cur.fetchone()
        if row is None:
            return ""
        s = str(row[0])
        return s[:60] + ("…" if len(s) > 60 else "")
    except Exception:
        cur.execute("ROLLBACK")
        return ""


def main() -> None:
    conn = psycopg2.connect(password=require_pg_password(), **DB_CONFIG)
    cur = conn.cursor()

    cur.execute(
        """
        SELECT table_name, table_type
        FROM information_schema.tables
        WHERE table_schema = %s
        ORDER BY table_name
        """,
        (RAW_SCHEMA,),
    )
    tables = cur.fetchall()

    lines: list[str] = [
        "# PUBG Raw Schema Audit",
        "",
        f"_Generated by `stdb/audit_raw.py` against `{RAW_SCHEMA}` schema._",
        "",
        f"- DB: `{DB_CONFIG['dbname']}` @ `{DB_CONFIG['host']}:{DB_CONFIG['port']}`",
        f"- Tables in `{RAW_SCHEMA}`: **{len(tables)}**",
        "",
    ]

    for tbl, ttype in tables:
        lines.append(f"## `{RAW_SCHEMA}.{tbl}` ({ttype})")

        cur.execute(
            """
            SELECT column_name, data_type, is_nullable, column_default
            FROM information_schema.columns
            WHERE table_schema = %s AND table_name = %s
            ORDER BY ordinal_position
            """,
            (RAW_SCHEMA, tbl),
        )
        cols = cur.fetchall()

        n = _table_rowcount(cur, RAW_SCHEMA, tbl)
        lines.append(f"- rows: **{n:,}**" if n is not None else "- rows: _n/a (view or error)_")
        lines.append("")
        lines.append("| Column | Type | Nullable | Default | Non-null sample |")
        lines.append("|---|---|---|---|---|")

        for cname, ctype, cnull, cdef in cols:
            sample = ""
            if ttype == "BASE TABLE" and n and n > 0:
                sample = _column_sample(cur, RAW_SCHEMA, tbl, cname)
            sample_md = sample.replace("|", "\\|") if sample else ""
            default_md = (cdef or "").replace("|", "\\|")
            lines.append(f"| `{cname}` | `{ctype}` | {cnull} | {default_md} | {sample_md} |")

        lines.append("")

    lines.append("## Quick match stats")
    try:
        cur.execute(f"SELECT count(*) FROM {RAW_SCHEMA}.matches")
        lines.append(f"- total matches: **{cur.fetchone()[0]:,}**")
    except Exception:
        cur.execute("ROLLBACK")

    try:
        cur.execute(
            f"""
            SELECT map_name, game_mode, count(*) AS n
            FROM {RAW_SCHEMA}.v_match_summary
            WHERE telemetry_fetched = true
            GROUP BY map_name, game_mode
            ORDER BY n DESC
            """
        )
        lines.append("")
        lines.append("| Map | Mode | Telemetry-fetched matches |")
        lines.append("|---|---|---|")
        for m, gm, c in cur.fetchall():
            lines.append(f"| `{m}` | `{gm}` | {c} |")
    except Exception as e:
        cur.execute("ROLLBACK")
        lines.append(f"_(v_match_summary query failed: {e})_")

    OUT_PATH.write_text("\n".join(lines) + "\n")
    print(f"Wrote {OUT_PATH} ({OUT_PATH.stat().st_size:,} bytes)")
    cur.close()
    conn.close()


if __name__ == "__main__":
    main()
